#!/usr/bin/env python3
"""Regenerate src/default_fonts.cpp: subsets the bundled fonts and embeds the bytes.

    pip install fonttools
    python3 tools/embed_fonts.py

Inter (UI text) keeps its pair kerning (GPOS 'kern'). JetBrains Mono (terminal / code) keeps the ranges
terminal programs draw with: box drawing, blocks, braille (btop/htop graphs), arrows, powerline symbols.
"""
import os, subprocess, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UI = "U+0020-007E,U+00A0-00FF,U+2010-2044,U+2190-2193,U+2212,U+25B2-25BC,U+2713-2717"
MONO = ("U+0020-007E,U+00A0-017F,U+2010-2044,U+2070-209F,U+20AC,U+2190-21FF,U+2200-22FF,U+2300-23FF,"
        "U+2500-257F,U+2580-259F,U+25A0-25FF,U+2600-26FF,U+2700-27BF,U+2800-28FF,U+E0A0-E0D4")
FONTS = [  # file, symbol, unicode ranges, layout features
    ("Inter-Regular.otf", "InterRegular", UI, "kern"),
    ("Inter-Medium.otf", "InterMedium", UI, "kern"),
    ("Inter-SemiBold.otf", "InterSemiBold", UI, "kern"),
    ("JetBrainsMono-Regular.ttf", "MonoRegular", MONO, ""),
    ("JetBrainsMono-Bold.ttf", "MonoBold", MONO, ""),
]

out = ['// Generated by tools/embed_fonts.py: Inter (SIL OFL 1.1) and JetBrains Mono (Apache-2.0); licenses in assets/fonts/. Subset.',
       '#include <cstddef>', '', 'namespace tg::fonts', '{']
with tempfile.TemporaryDirectory() as tmp:
    for src, name, unicodes, features in FONTS:
        dst = os.path.join(tmp, name + os.path.splitext(src)[1])
        subprocess.check_call(["pyftsubset", os.path.join(ROOT, "assets/fonts", src), "--unicodes=" + unicodes,
                               "--layout-features=" + features, "--output-file=" + dst])
        data = open(dst, "rb").read()
        out.append("    extern const unsigned char %s[] = {" % name)
        for i in range(0, len(data), 24):
            out.append("        " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        out.append("    };")
        out.append("    extern const size_t %sSize = sizeof( %s );" % (name, name))
        print("%-28s %7d bytes" % (src, len(data)))
out.append("}")
open(os.path.join(ROOT, "src/default_fonts.cpp"), "w").write("\n".join(out) + "\n")
print("wrote src/default_fonts.cpp")
