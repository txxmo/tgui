#!/usr/bin/env python3
"""Regenerate src/default_fonts.cpp: subsets Inter to the glyphs tg bakes and embeds the bytes.

    pip install fonttools
    python3 tools/embed_fonts.py
"""
import os, subprocess, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UNICODES = "U+0020-007E,U+00A0-00FF,U+2010-2044,U+2190-2193,U+2212,U+25B2-25BC,U+2713-2717"
FONTS = [("Regular", "InterRegular"), ("SemiBold", "InterSemiBold")]

out = ['// Generated by tools/embed_fonts.py — Inter (SIL OFL 1.1, see assets/fonts/LICENSE-Inter.txt), subset.',
       '#include <cstddef>', '', 'namespace tg::fonts', '{']
with tempfile.TemporaryDirectory() as tmp:
    for style, name in FONTS:
        dst = os.path.join(tmp, style + ".otf")
        subprocess.check_call(["pyftsubset", os.path.join(ROOT, "assets/fonts/Inter-%s.otf" % style),
                               "--unicodes=" + UNICODES, "--layout-features=", "--output-file=" + dst])
        data = open(dst, "rb").read()
        out.append("    extern const unsigned char %s[] = {" % name)
        for i in range(0, len(data), 24):
            out.append("        " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        out.append("    };")
        out.append("    extern const size_t %sSize = sizeof( %s );" % (name, name))
out.append("}")
open(os.path.join(ROOT, "src/default_fonts.cpp"), "w").write("\n".join(out) + "\n")
print("wrote src/default_fonts.cpp")
