#!/usr/bin/env python3
"""Compile backends/vk_shaders/*.vert|frag to SPIR-V and embed them in backends/vk_shaders.inc.
Needs glslangValidator (Vulkan SDK / `apt install glslang-tools`). Run after editing a shader."""
import os, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "backends", "vk_shaders")
OUT = os.path.join(ROOT, "backends", "vk_shaders.inc")

parts = ["// Generated by tools/compile_vk_shaders.py from backends/vk_shaders/ - don't edit.\n"]
for name in sorted(os.listdir(SRC)):
    if not name.endswith((".vert", ".frag")):
        continue
    var = "Spv_" + name.replace(".", "_")
    with tempfile.TemporaryDirectory() as t:
        spv = os.path.join(t, "out.spv")
        subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.0", "-o", spv, os.path.join(SRC, name)], check=True, stdout=subprocess.DEVNULL)
        data = open(spv, "rb").read()
    words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
    lines = [", ".join("0x%08x" % w for w in words[i:i + 8]) for i in range(0, len(words), 8)]
    parts.append("static const uint32_t %s[] = {\n    %s\n};\n" % (var, ",\n    ".join(lines)))
open(OUT, "w", newline="\n").write("".join(parts))
print("wrote", OUT)
